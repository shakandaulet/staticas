def _e_flow_domain(op: ResolvedOp, domain: str) -> list[str]:
    """Flow Simulation project creation.

    Emitted as a recorded, refusing stub rather than as invented COM
    calls. Writing plausible-looking Flow Simulation API calls that were
    never run would produce a script that fails somewhere in the middle,
    after creating a project, with a COM error naming a method the user
    has never heard of. Stating the limit up front and writing the
    complete setup into the receipt is more useful: the user can build
    the project through the wizard in about a minute with every number
    already decided and checked."""
    settings = {
        "analysis_type": op.options.get("analysis_type", "internal"),
        "fluid": op.options.get("fluid", "Air"),
        "flow_type": op.options.get("flow_type", "laminar_and_turbulent"),
        "heat_conduction": op.options.get("heat_conduction", "off"),
        "gravity": op.options.get("gravity", "off"),
        "time": op.options.get("time", "steady"),
        "ambient_pressure_Pa": op.num("ambient_pressure", 101325.0),
        "ambient_temperature_K": op.num("ambient_temperature", 293.15),
        "velocity_m_s": op.num("velocity", 0.0),
        "turbulence_intensity_pct": op.num("turbulence_intensity", 0.0),
    }
    return [f'    RECEIPT["flow_project"] = {_py(settings)}']


def _e_flow_bc(op: ResolvedOp, domain: str) -> list[str]:
    bc = {
        "type": op.options.get("type", ""),
        "target": op.target.describe() if op.target else "",
        **{k: v.value for k, v in op.q.items()},
    }
    return [f'    RECEIPT.setdefault("flow_bcs", []).append({_py(bc)})']


def _e_goal(op: ResolvedOp, domain: str) -> list[str]:
    goal = {"quantity": op.options.get("quantity", ""),
            "scope": op.options.get("scope", "global"),
            "target": op.target.describe() if op.target else "whole model"}
    return [f'    RECEIPT.setdefault("goals", []).append({_py(goal)})']


def _e_frequency_options(op: ResolvedOp, domain: str) -> list[str]:
    """How many modes to extract.

    Through the runtime helper rather than inline: ICWStudy has no
    SetFrequencyOptions method at all, which is what this used to call,
    so the mode count quietly stayed at the study's default."""
    modes = int(op.num("modes", 5) or 5)
    return [f"    set_frequency_modes(study, {modes}, {_py(domain)})"]


def _e_solve(op: ResolvedOp, domain: str) -> list[str]:
    if D.DOMAINS[domain].engine == D.FLOW:
        # The checklist goes out first -- boundary conditions and goals are
        # recorded by now -- then the part's own project, if it has one.
        return [
            "    print_flow_setup(RECEIPT)",
            '    project = flow_project(app, model, RECEIPT.get("flow_project"))',
            "    if project is not None:",
            "        solve_flow(project)",
        ]
    return ["    solve(study)"]


def _e_results(op: ResolvedOp, domain: str) -> list[str]:
    if D.DOMAINS[domain].engine == D.FLOW:
        return ["    if project is not None:",
                "        read_flow_goals(project)",
                "    write_receipt()"]
    return [
        f"    read_results(study, {_py(domain)})",
        f"    save_plots(study, {_py(domain)})",
        "    keep_part()",
        "    write_receipt()",
    ]


def _e_custom(op: ResolvedOp, domain: str) -> list[str]:
    """A custom step is the one place generated code can enter.

    It is emitted as a refusing placeholder here; the server fills it in
    from a separate, RAG-grounded generation pass and re-validates the
    whole script afterwards. Emitting a stub rather than silently
    dropping the step means a plan that depended on it cannot run and
    quietly skip the thing the user asked for."""
    instruction = op.options.get("instruction", "")
    return [
        f"    # CUSTOM STEP -- generated separately: {instruction}",
        f"    raise RuntimeError({_py('Custom step was not filled in: ' + instruction)})",
    ]


