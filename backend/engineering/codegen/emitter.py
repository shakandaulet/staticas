def supported_ops() -> set[str]:
    """Which operations to offer the planner, and to accept in a plan.

    `custom` is deliberately not in here. It emits a placeholder that
    raises, because the RAG-grounded generation pass meant to fill it in
    does not exist -- so a plan carrying one produces a script that
    builds the study, applies the loads and then dies before solving.
    Left out, the model is never offered it, and unsupported() refuses a
    plan that contains one by some other route."""
    return set(_EMITTERS) - {"custom"}


def unsupported(ops: list[ResolvedOp]) -> list[str]:
    """Operations in this plan that the emitter cannot write yet.

    The catalogue is deliberately wider than the emitter. Recognising
    "spin it at 3000 rpm" as a centrifugal load and saying so beats
    failing to understand it -- but the gap has to be surfaced at PLAN
    time, as a sentence in the panel, rather than at run time as a
    script that stops halfway through.

    Derived from supported_ops() rather than from a second flag on the
    spec, because two lists of the same thing drift apart and the one
    that drifts is always the one nothing tests."""
    return sorted({op.op for op in ops if op.op not in supported_ops()})


def order_ops(ops: list[ResolvedOp]) -> list[ResolvedOp]:
    """Put the plan in an order SolidWorks will accept.

    The model produces steps in the order the user said them, which is
    the order a person thinks in and not the order the API requires:
    a material cannot be assigned before a study exists, loads cannot be
    applied before a mesh, and nothing can be read before a solve. Sorting
    here means the planner never has to be told about sequencing, which
    is one fewer instruction for it to half-follow."""
    rank = {
        "set_geometry": 0, "set_flow_domain": 1, "apply_material": 2,
        "set_solver": 3, "set_frequency_options": 3, "set_mesh": 4,
        "add_fixture": 5,
        "add_force": 6, "add_pressure": 6, "add_torque": 6,
        "add_gravity": 6, "add_centrifugal": 6, "add_bearing_load": 6,
        "add_remote_load": 6, "add_initial_velocity": 6,
        "add_temperature": 6, "add_convection": 6, "add_heat_flux": 6,
        "add_heat_power": 6, "add_radiation": 6,
        "add_flow_bc": 6, "add_fan": 6, "add_porous_medium": 6,
        "add_rotating_region": 6, "add_goal": 7,
        "custom": 8, "solve": 9, "extract_results": 10,
    }
    return sorted(ops, key=lambda o: rank.get(o.op, 6))
