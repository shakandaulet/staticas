"""
Plan -> standalone Python. Deterministically.

WHY THE MODEL DOES NOT WRITE THIS CODE
--------------------------------------
Given a plan, there is exactly one right script, and producing it is
string formatting. Handing that to a language model adds a failure mode
(it forgets the VARIANT null, it adds parentheses to ForceEndEdit, it
helpfully refines the mesh) and buys nothing, because there was no
judgement left to exercise by the time the plan existed.

So the split is: the model decides WHAT to simulate, this file decides
HOW to write it, and the runtime prelude -- which neither of them
touches -- decides how to talk to COM. The only path back to generated
code is the `custom` operation, which is marked as such everywhere it
appears.

THE EMITTED SCRIPT IS STANDALONE
--------------------------------
It inlines the prelude rather than importing it, so a student can
download one file and run it on a machine that has never heard of this
project. That is also why the mesh floor is re-checked inside the
emitted file: once it is downloaded it is out of this project's hands,
and the check has to travel with it.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from datetime import datetime

from .. import config
from ..core import domains as D
from ..core.ops import ResolvedOp

_PRELUDE_RE = re.compile(
    r"# --- BEGIN RUNTIME PRELUDE.*?\n(.*?)\n# --- END RUNTIME PRELUDE ---",
    re.DOTALL)


def _prelude() -> str:
    """The runtime, read out of templates/runtime.py at emit time.

    Read rather than duplicated so there is one copy to fix when a COM
    quirk turns out to be wrong. The markers exist so the file stays a
    normal, importable, testable module instead of a blob of text."""
    source = (config.TEMPLATES_DIR / "runtime.py").read_text(encoding="utf-8")
    m = _PRELUDE_RE.search(source)
    if not m:
        raise RuntimeError(
            "templates/runtime.py is missing its PRELUDE markers. The "
            "emitter reads the runtime out of that file rather than "
            "keeping a second copy.")
    return m.group(1)


@dataclass
class Emitted:
    code: str
    domain: str
    unverified_ops: list[str]
    notes: list[str]


def _py(value) -> str:
    """A Python literal for a plan value. json.dumps handles the quoting
    and the unicode, and every value here is JSON-shaped by construction."""
    return json.dumps(value, ensure_ascii=False)


def _sel(op: ResolvedOp) -> str:
    if op.target is None:
        return "None"
    data = op.target.model_dump()
    data.pop("said", None)
    return _py({k: v for k, v in data.items() if v not in (None, "", [])})


def emit(domain: str, ops: list[ResolvedOp], study_name: str = "AI_Study",
         summary: str = "", assumptions: list[str] | None = None,
         warnings: list[str] | None = None,
         converge: bool = False) -> Emitted:
    spec = D.DOMAINS[domain]
    lines: list[str] = []
    notes: list[str] = []
    unverified = [o.op for o in ops if o.spec.confidence == "unverified"]

    # ---------------- header ----------------
    head = [
        '"""',
        f"Generated by the engineering assistant on "
        f"{datetime.now().strftime('%Y-%m-%d %H:%M')}.",
        "",
        f"Study: {study_name}   Domain: {spec.label}",
    ]
    if summary:
        head += ["", f"Question: {summary}"]
    head += ["", "Plan:"]
    head += [f"  {i + 1}. {o.note or o.spec.label}" for i, o in enumerate(ops)]

    all_assumptions = list(assumptions or [])
    for o in ops:
        all_assumptions.extend(o.assumptions)
    if all_assumptions:
        head += ["", "Assumptions -- each of these is somewhere the answer",
                 "could be wrong for a reason you can see and correct:"]
        head += [f"  - {a}" for a in dict.fromkeys(all_assumptions)]
    if warnings:
        head += ["", "Warnings:"] + [f"  - {w}" for w in warnings]
    if unverified:
        head += [
            "",
            "API CONFIDENCE: this script uses calls that have NOT been run",
            "against a licensed install by this project:",
            f"  {', '.join(sorted(set(unverified)))}",
            "Review it before running it on a machine that matters. The",
            "physics and the numbers are checked; the COM signatures for",
            "these particular calls are reconstructed from documentation.",
        ]
    if spec.type_confidence == "unverified" and spec.study_type is not None:
        head += [
            "",
            f"The study type constant for {spec.label} ({spec.study_type}) is",
            "documented but unconfirmed here. The script reads the type back",
            "off the created study and stops if it does not match, so a wrong",
            "constant fails immediately instead of answering a different",
            "question.",
        ]
    head += ['"""', ""]

    lines.extend(head)
    lines.append(_prelude())
    lines.append("")
    lines.append("")
    lines.append("# " + "-" * 72)
    lines.append("# The plan")
    lines.append("# " + "-" * 72)
    lines.append("def main():")
    lines.append('    RECEIPT["domain"] = ' + _py(domain))
    lines.append('    RECEIPT["summary"] = ' + _py(summary))
    lines.append("    app = connect_to_solidworks()")

    ops = order_ops(ops)
    body: list[str] = []

    # Geometry comes first, then the add-in connection, then everything
    # else. The connection has to sit between them: Simulation binds to
    # whichever document is active, so connecting before the part exists
    # gives a study attached to nothing.
    if not any(o.op == "set_geometry" for o in ops):
        body += ["",
                 "    # No geometry step in the plan: use whatever is open.",
                 "    model = active_part(app)"]
    else:
        for op in [o for o in ops if o.op == "set_geometry"]:
            body.extend(_emit_op(op, domain))

    if any(o.target is not None and o.target.kind == "active_selection"
           for o in ops):
        # Read before anything else runs: a directional force selects a
        # reference plane, and that clears what the user picked.
        body += ["",
                 "    # What you have selected in SolidWorks, read first.",
                 "    capture_selection(model)"]

    body.append("")
    body.extend(_engine_setup(domain, study_name))

    for op in [o for o in ops if o.op != "set_geometry"]:
        body.extend(_emit_op(op, domain))

    if not any("write_receipt" in b for b in body):
        body += ["", "    write_receipt()"]

    wants_check = converge or any(
        o.op == "set_mesh" and o.options.get("convergence") == "check"
        for o in ops)
    if wants_check and spec.engine != D.FLOW and "    write_receipt()" in body:
        # After the first answer is read and before the plots and the
        # receipt: the check re-solves and keeps the finer result, and the
        # pictures should show that one.
        plots = f"    save_plots(study, {_py(domain)})"
        at = body.index(plots if plots in body else "    write_receipt()")
        body[at:at] = [f"    check_convergence(study, {_py(domain)})"]

    lines.extend(body)
    lines.append("")
    lines.append("")
    lines.append('if __name__ == "__main__":')
    lines.append("    try:")
    lines.append("        main()")
    lines.append("    except Exception as exc:")
    lines.append("        fail(exc)")
    lines.append("")

    return Emitted(code="\n".join(lines), domain=domain,
                   unverified_ops=sorted(set(unverified)), notes=notes)


