def _emit_op(op: ResolvedOp, domain: str) -> list[str]:
    fn = _EMITTERS.get(op.op)
    if fn is None:
        # A step with no emitter must NOT become a comment. The
        # catalogue is wider than the emitter on purpose -- recognising
        # "spin it at 3000 rpm" and saying the centrifugal load is not
        # wired up yet is more useful than not understanding it at all
        # -- but a script that silently skips a step the user asked for
        # runs, finishes, and answers a different question.
        #
        # The server refuses to emit at all when unsupported() is
        # non-empty; this is the second line of defence, for a script
        # emitted by some other path.
        return [
            f"    raise RuntimeError("
            f"{_py(f'This plan needs {op.spec.label} ({op.op}), which is in '
                   f'the operation catalogue but has no emitter yet. The '
                   f'step was NOT applied and the study was not run.')})"
        ]
    out = [""]
    if op.note:
        out.append(f"    # {op.note}")
    out.extend(fn(op, domain))
    return out


def _e_geometry(op: ResolvedOp, domain: str) -> list[str]:
    source = op.options.get("source", "active_document")
    if source == "active_document":
        return [
            "    model = active_part(app)",
            '    RECEIPT["geometry"] = {"source": "active_document"}',
        ]
    shape = op.options.get("primitive", "rectangular_beam")
    builder = PRIMITIVES.get(shape)
    if builder is None:
        return ["    model = new_part(app)",
                f"    raise RuntimeError("
                f"'No builder for primitive {shape}. Model it in "
                f"SolidWorks and re-run with source=active_document.')"]
    fn, args = builder
    values = ", ".join(repr(op.num(name, default)) for name, default in args)
    return ["    model = new_part(app)",
            f'    RECEIPT["geometry"] = {fn}(model, {values})']


# Every primitive the catalogue offers, with the runtime builder that
# makes it and the slots it reads in order (with the default each falls
# back to, in metres). The catalogue used to offer i_beam, box and
# cylinder with nothing here to build them: the plan was accepted, the
# script was written, and it stopped in SolidWorks on "No builder". A
# test now holds the two lists together.
PRIMITIVES: dict[str, tuple[str, tuple[tuple[str, float], ...]]] = {
    "rectangular_beam": ("build_rectangular_beam", (
        ("width", 0.05), ("height", 0.1), ("length", 1.0))),
    "box": ("build_box", (
        ("width", 0.05), ("height", 0.1), ("length", 1.0), ("wall", 0.0))),
    "round_bar": ("build_round_bar", (("diameter", 0.05), ("length", 1.0))),
    "cylinder": ("build_round_bar", (("diameter", 0.05), ("length", 1.0))),
    "tube": ("build_tube", (
        ("outer_diameter", 0.06), ("wall", 0.005), ("length", 1.0))),
    "i_beam": ("build_i_beam", (
        ("flange_width", 0.1), ("height", 0.2), ("web_thickness", 0.008),
        ("flange_thickness", 0.012), ("length", 2.0))),
    "plate": ("build_plate", (
        ("width", 0.2), ("length", 0.3), ("thickness", 0.005))),
    "plate_with_hole": ("build_plate_with_hole", (
        ("width", 0.1), ("length", 0.3), ("thickness", 0.01),
        ("hole_diameter", 0.025))),
    "angle_bracket": ("build_angle_bracket", (
        ("length", 0.12), ("height", 0.1), ("width", 0.06),
        ("thickness", 0.01), ("fillet_radius", 0.0),
        ("hole_diameter", 0.0))),
}


def _engine_setup(domain: str, study_name: str) -> list[str]:
    """Connect the right add-in and create the study.

    Which add-in depends on the domain, not on the operations: fluid
    mechanics and aerodynamics go through Flow Simulation, which is a
    different product from the Simulation add-in that everything else
    uses, with no study-type code and no shared object model."""
    if D.DOMAINS[domain].engine == D.FLOW:
        # No add-in connection yet. The checklist is printed first and the
        # connection happens at the solve step, so a machine with the
        # add-in switched off still gets the checklist.
        return [
            "    # Fluid domains go through the Flow Simulation add-in. This",
            "    # script prints the wizard checklist, then solves the part's",
            "    # Flow project and reads its goals -- if the project exists.",
            "    project = None",
        ]
    return [
        "    cw = connect_simulation(app)",
        f"    study = create_study(cw, {_py(study_name)}, {_py(domain)})",
    ]


def _e_material(op: ResolvedOp, domain: str) -> list[str]:
    name = op.options.get("name", "Plain Carbon Steel")
    db = op.options.get("database", "")
    return [f"    apply_material(study, {_py(name)}, {_py(db)})"]


def _e_mesh(op: ResolvedOp, domain: str) -> list[str]:
    if D.DOMAINS[domain].engine == D.FLOW:
        # Flow meshes are counted in cells and set through the project
        # wizard, not by element size. The level is recorded rather than
        # applied, for the same reason the project itself is: writing
        # unverified wizard calls would fail halfway through setup.
        level = int(op.num("level", 3) or 3)
        cells = int(op.num("max_cells", config.FLOW_MAX_CELLS)
                    or config.FLOW_MAX_CELLS)
        return [
            f'    RECEIPT["mesh"] = {_py({"level": level, "max_cells": cells})}',
            f"    warn('Initial mesh level {level} (cap {cells:,} cells) is "
            f"recorded in the receipt, not applied: the Flow Simulation "
            f"wizard API is not verified on this install. Set it in the "
            f"wizard.')",
        ]
    # Element sizes are held in millimetres and floored on both sides.
    max_mm = op.num("max_element", 0.0) * 1000.0 or 50.0
    min_mm = op.num("min_element", 0.0) * 1000.0 or 2.5
    max_mm = max(max_mm, config.MESH_MAX_ELEMENT_FLOOR_MM)
    min_mm = max(min_mm, config.MESH_MIN_ELEMENT_FLOOR_MM)
    # swsMeshQuality_e: draft 0, high 1. This line had them swapped, so
    # "draft" meshed second-order and "high" first-order.
    quality = "MESH_DRAFT" if op.options.get("quality") == "draft" else "MESH_HIGH"
    return [f"    create_mesh(study, {max_mm!r}, {min_mm!r}, {quality})"]


def _e_fixture(op: ResolvedOp, domain: str) -> list[str]:
    kind = op.options.get("type", "fixed")
    what = _py(op.note or f"the {kind} restraint")
    return [
        f"    entities = resolve(model, {_sel(op)}, {what})",
        f"    add_restraint(study, entities, {_py(kind)}, {what})",
    ]


def _e_force(op: ResolvedOp, domain: str) -> list[str]:
    """A force, with the direction the plan asked for.

    The direction used to be dropped here, so every load went on normal
    to the selected face. On the end face of a beam that is along the
    span -- the load compresses the beam instead of bending it, and the
    study solves and reports a stress that answers nothing."""
    per_entity = op.options.get("distribution") == "per_entity"
    direction = op.options.get("direction", "normal")
    what = _py(op.note or "the force")
    return [
        f"    entities = resolve(model, {_sel(op)}, {what})",
        f"    add_force(study, model, entities, {op.num('magnitude')!r}, "
        f"{_py(direction)}, {per_entity!r}, {what})",
    ]


